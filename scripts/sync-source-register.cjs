/* Regenerate after evidence changes. Review dates are never inferred from publication dates. */
const fs=require('node:fs'),vm=require('node:vm');
const files=['data.js','product-data.js','guidance-data.js','environment-data.js','editions-data.js'];
const day=process.env.SOURCE_REGISTER_DATE||new Intl.DateTimeFormat('en-CA',{timeZone:'America/New_York',year:'numeric',month:'2-digit',day:'2-digit'}).format(new Date());
const context={window:{}};vm.createContext(context);
for(const f of files)vm.runInContext(fs.readFileSync('dist/'+f,'utf8'),context);
const target='dist/source-register.js';
let previous={sources:[]};if(fs.existsSync(target)){const c={window:{}};vm.runInNewContext(fs.readFileSync(target,'utf8'),c);previous=c.window.VersionCompassSources;}
const notes=JSON.parse(fs.readFileSync('docs/source-annotations.json','utf8'));
const rows=new Map(),date=v=>/^\d{4}-\d{2}-\d{2}$/.test(v||'')?v:null;
function add(url,obj,area,path){
 if(!/^https:\/\//.test(url))return;
 const old=rows.get(url)||{url,title:obj.title||obj.t||decodeURIComponent(new URL(url).pathname.split('/').filter(Boolean).pop()||new URL(url).hostname).replace(/[-_]/g,' '),areas:[],references:[],reviews:[]};
 if(!old.areas.includes(area))old.areas.push(area);
 if(!old.references.includes(path))old.references.push(path);
 const reviewed=date(obj.checked)||date(obj.reviewed);if(reviewed&&!old.reviews.includes(reviewed))old.reviews.push(reviewed);
 rows.set(url,old);
}
function walk(value,area,path,parent={}){
 if(typeof value==='string'){if(value.startsWith('https://'))add(value,parent,area,path);return;}
 if(!value||typeof value!=='object')return;
 for(const [key,v] of Object.entries(value))walk(v,area,path+'.'+key,value);
}
walk(context.window.SPLUNK_DATA,'Release guide','release');
walk(context.window.VersionCompassEnvironmentData,'Cloud environment','environment');
walk(context.window.VersionCompassEditions,'ES editions','editions');
// Include directly embedded official citations as well as data-driven citations.
for(const f of fs.readdirSync('dist').filter(f=>f.endsWith('.js')&&!['source-register.js','about.js',...files].includes(f))){
 const text=fs.readFileSync('dist/'+f,'utf8');
 for(const m of text.matchAll(/https:\/\/(?:[a-z0-9-]+\.)*(?:splunk\.com|cisco\.com|fedramp\.gov|nist\.gov)\/[^\s"'\x60<>]+/g))add(m[0],{},'Shared guidance',f);
}
// Resolve catalog identifiers to the records that consume them and surface disagreements.
function resolveReferences(root,area){
 const catalog=root.sources||{};
 function visit(value,path,conflict=false){
  if(!value||typeof value!=='object')return;
  conflict=conflict||value.availability==='conflicting'||path.includes('.conflicts.');
  for(const [key,v] of Object.entries(value)){
   if(['src','sources'].includes(key)&&Array.isArray(v))for(const id of v){
    const source=catalog[id],row=source&&rows.get(source.url||source.u);
    if(row){const location=area+': '+path;if(!row.references.includes(location))row.references.push(location);if(conflict)row.conflict=true;}
   }
   if(key!=='sources'||Array.isArray(v))visit(v,path+'.'+key,conflict);
  }
 }
 visit(root,area);
}
resolveReferences(context.window.VersionCompassEnvironmentData,'environment');
resolveReferences(context.window.VersionCompassEditions,'editions');
const prior=new Map(previous.sources.map(r=>[r.url,r]));
const sources=[...rows.values()].map(r=>{
 const p=prior.get(r.url),note=notes[r.url]||{},events=p?.events||[];
 if(!p)events.push({date:day,event:'First recorded in source register; earlier usage date not established'});
 else if(p.usage!=='In use')events.push({date:day,event:'Returned to use'});
 const reviewed=note.reviewed||r.reviews.sort().at(-1)||null;
 const status=note.outdatedAsOf?'Out of date':(note.conflict||r.conflict)?'Needs reconciliation':reviewed?'Reviewed':'Review date unknown';
 if(p&&(p.status!==status||p.reviewed!==reviewed||p.verificationScope!==(note.verificationScope||'')))events.push({date:day,event:'Review status updated: '+status+(reviewed?' · '+reviewed:'')});
 return {...r,usage:'In use',reviewed,status,firstRecorded:p?.firstRecorded||day,firstUsed:note.firstUsed||p?.firstUsed||null,outdatedAsOf:note.outdatedAsOf||null,reason:note.reason||'',section:note.section||'',verificationScope:note.verificationScope||'',events};
});
for(const p of previous.sources)if(!rows.has(p.url))sources.push({...p,usage:'Retired',events:p.usage==='Retired'?p.events:[...p.events,{date:day,event:'No longer cited in the maintained datasets'}]});
sources.sort((a,b)=>a.url.localeCompare(b.url));
const output='/* Generated by scripts/sync-source-register.cjs; retain historical entries. */\nwindow.VersionCompassSources = '+JSON.stringify({schemaVersion:1,trackingSince:previous.trackingSince||day,sources},null,2)+';\n';
if(process.argv.includes('--check')){if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==output){console.error('Source register needs synchronization');process.exit(1)}}else fs.writeFileSync(target,output);
console.log(sources.length+' sources registered');
